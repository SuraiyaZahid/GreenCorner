<?php
/**
 * GreenCorner — Order Model
 *
 * Data access for the `orders` and `order_items` tables, and the generation
 * of the human-readable order number.
 *
 * Implements:
 *   FR-4.8  the delivery address is stored as an immutable snapshot on the
 *           order row
 *   FR-4.11 stock and price are re-validated inside the checkout transaction,
 *           with the product rows locked using SELECT ... FOR UPDATE
 *   FR-4.12 the order line records the price at purchase as an immutable
 *           snapshot, so a later price change never alters a stored order
 *   FR-4.13 the confirmation page reads the order and its items
 *   FR-4.14 every order carries a unique, human-readable order number
 *   FR-4.15 the order, its items and the stock reduction succeed together or
 *           not at all
 *   FR-4.16 the payment status is owned by `payments`; this model never
 *           stores a copy of it
 *   FR-5.1  the customer's orders, most recent first
 *   FR-5.2  a single order with its items, for the order detail page
 *
 * The order number format (decision C) is GC-YYYYMMDD-NNNN, for example
 * GC-20261102-0007. The sequence is generated by a daily counter that is
 * locked with SELECT ... FOR UPDATE, so two simultaneous checkouts can never
 * receive the same number (decision D).
 */

require_once __DIR__ . '/../helpers/db.php';

class Order
{
    /**
     * The prefix every order number carries (decision C).
     */
    public const NUMBER_PREFIX = 'GC';

    /**
     * The number of orders shown on one page of the customer's order list.
     */
    public const PER_PAGE = 10;

    /**
     * The current time, formatted for a DATETIME column.
     *
     * @return string 'Y-m-d H:i:s'.
     */
    public static function now(): string
    {
        return date('Y-m-d H:i:s');
    }

    // -----------------------------------------------------------------------
    // The order number
    // -----------------------------------------------------------------------

    /**
     * Generate the next order number for today.
     *
     * The counter row for the current date is locked with
     * `SELECT ... FOR UPDATE` before it is read, so two concurrent
     * transactions cannot both read the same value and produce the same
     * order number (decision D).
     *
     * The caller must already be inside a transaction: the lock is only
     * held until that transaction ends. The lock therefore also serialises
     * the rest of the checkout, which is what FR-4.11 needs.
     *
     * @param string|null $date The date to use, 'Y-m-d'. Defaults to today.
     * @return string The order number, e.g. 'GC-20261102-0007'.
     */
    public static function nextNumber(?string $date = null): string
    {
        $date = $date ?? date('Y-m-d');

        // Make sure the row for this date exists. The silent-error INSERT
        // variant is not used (R-SQL-7); the row is created only when it is
        // genuinely absent, and a duplicate key from a concurrent insert is
        // not treated as an error.
        db_write(
            'INSERT INTO `order_sequence` (`sequence_date`, `last_value`)
             VALUES (?, 0)
             ON DUPLICATE KEY UPDATE `last_value` = `last_value`',
            's',
            array($date)
        );

        // Lock the counter row for the rest of the transaction.
        $row = db_select_one(
            'SELECT `last_value` FROM `order_sequence`
              WHERE `sequence_date` = ?
              FOR UPDATE',
            's',
            array($date)
        );

        $next = ((int) ($row['last_value'] ?? 0)) + 1;

        db_write(
            'UPDATE `order_sequence` SET `last_value` = ? WHERE `sequence_date` = ?',
            'is',
            array($next, $date)
        );

        return self::NUMBER_PREFIX . '-' . str_replace('-', '', $date) . '-' . str_pad((string) $next, 4, '0', STR_PAD_LEFT);
    }

    /**
     * The number of orders, including cancelled ones (FR-6.1).
     *
     * @return int
     */
    public static function countAll(): int
    {
        $row = db_select_one('SELECT COUNT(*) AS `total` FROM `orders`');

        return (int) ($row['total'] ?? 0);
    }

    // -----------------------------------------------------------------------
    // The Admin order list (P-17)
    // -----------------------------------------------------------------------

    /**
     * The number of orders shown on one page of the Admin order list.
     */
    public const ADMIN_PER_PAGE = 20;

    /**
     * One page of the Admin order list (FR-6.7).
     *
     * Every order is listed, including cancelled ones. The customer's name
     * and the payment status are joined in, because FR-6.7 requires both to
     * be shown. The payment status is read from `payments.status`, which is
     * the sole source of payment status (FR-4.16).
     *
     * @param int $limit
     * @param int $offset
     * @return array<int, array<string, mixed>>
     */
    public static function listAll(int $limit = self::ADMIN_PER_PAGE, int $offset = 0): array
    {
        $limit = max(1, min($limit, 100));
        $offset = max(0, $offset);

        return db_select(
            "SELECT o.`id`, o.`order_number`, o.`user_id`, o.`total_amount`,
                    o.`status`, o.`created_at`,
                    u.`full_name` AS `customer_name`,
                    u.`email` AS `customer_email`,
                    p.`method` AS `payment_method`,
                    p.`status` AS `payment_status`
               FROM `orders` o
               JOIN `users` u ON u.`id` = o.`user_id`
          LEFT JOIN `payments` p ON p.`order_id` = o.`id`
              ORDER BY o.`created_at` DESC, o.`id` DESC
              LIMIT ? OFFSET ?",
            'ii',
            array($limit, $offset)
        );
    }

    /**
     * The number of pages needed for the Admin order list.
     *
     * @param int $totalResults
     * @param int $perPage
     * @return int
     */
    public static function adminPageCount(int $totalResults, int $perPage = self::ADMIN_PER_PAGE): int
    {
        $perPage = max(1, $perPage);

        if ($totalResults <= 0) {
            return 1;
        }

        return (int) ceil($totalResults / $perPage);
    }

    // -----------------------------------------------------------------------
    // Reading orders
    // -----------------------------------------------------------------------

    /**
     * Find one order by id, with its payment status and its customer.
     *
     * The payment status is joined from `payments`, which is the sole owner
     * of that status (FR-4.16). A card order always has exactly one
     * payment row; a COD order has one as well.
     *
     * The customer's name and email address are joined from `users`, so the
     * Admin Order Detail page can show who the order belongs to (FR-6.8).
     *
     * @param int $id
     * @return array<string, mixed>|null
     */
    public static function find(int $id): ?array
    {
        return db_select_one(
            "SELECT o.`id`, o.`order_number`, o.`user_id`, o.`total_amount`,
                    o.`status`, o.`delivery_name`, o.`delivery_phone`,
                    o.`delivery_address`, o.`delivery_city`, o.`created_at`,
                    u.`full_name` AS `customer_name`,
                    u.`email` AS `customer_email`,
                    p.`method` AS `payment_method`, p.`status` AS `payment_status`,
                    p.`paid_at`
               FROM `orders` o
          LEFT JOIN `users` u ON u.`id` = o.`user_id`
          LEFT JOIN `payments` p ON p.`order_id` = o.`id`
              WHERE o.`id` = ?
              LIMIT 1",
            'i',
            array($id)
        );
    }

    /**
     * Find one order by its human-readable order number.
     *
     * @param string $orderNumber
     * @return array<string, mixed>|null
     */
    public static function findByNumber(string $orderNumber): ?array
    {
        return db_select_one(
            "SELECT o.`id`, o.`order_number`, o.`user_id`, o.`total_amount`,
                    o.`status`, o.`delivery_name`, o.`delivery_phone`,
                    o.`delivery_address`, o.`delivery_city`, o.`created_at`,
                    p.`method` AS `payment_method`, p.`status` AS `payment_status`,
                    p.`paid_at`
               FROM `orders` o
          LEFT JOIN `payments` p ON p.`order_id` = o.`id`
              WHERE o.`order_number` = ?
              LIMIT 1",
            's',
            array($orderNumber)
        );
    }

    /**
     * The items of an order.
     *
     * The product name and unit price are the immutable purchase-time
     * snapshot (FR-4.12, BR-6), so they are read from `order_items` and
     * never from the live product row.
     *
     * @param int $orderId
     * @return array<int, array<string, mixed>>
     */
    public static function items(int $orderId): array
    {
        return db_select(
            'SELECT `id`, `order_id`, `product_id`, `product_name_at_purchase`,
                    `unit_price_at_purchase`, `quantity`
               FROM `order_items`
              WHERE `order_id` = ?
              ORDER BY `id` ASC',
            'i',
            array($orderId)
        );
    }

    /**
     * The line total of an order item.
     *
     * @param array<string, mixed> $item An order_items row.
     * @return float
     */
    public static function lineTotal(array $item): float
    {
        return round((float) $item['unit_price_at_purchase'] * (int) $item['quantity'], 2);
    }

    /**
     * The orders of one customer, most recent first (FR-5.1).
     *
     * @param int $userId
     * @param int $limit
     * @param int $offset
     * @return array<int, array<string, mixed>>
     */
    public static function forUser(int $userId, int $limit = self::PER_PAGE, int $offset = 0): array
    {
        $limit = max(1, min($limit, 100));
        $offset = max(0, $offset);

        return db_select(
            "SELECT o.`id`, o.`order_number`, o.`total_amount`, o.`status`,
                    o.`created_at`,
                    p.`method` AS `payment_method`, p.`status` AS `payment_status`
               FROM `orders` o
          LEFT JOIN `payments` p ON p.`order_id` = o.`id`
              WHERE o.`user_id` = ?
              ORDER BY o.`created_at` DESC, o.`id` DESC
              LIMIT ? OFFSET ?",
            'iii',
            array($userId, $limit, $offset)
        );
    }

    /**
     * The number of orders belonging to one customer.
     *
     * @param int $userId
     * @return int
     */
    public static function countForUser(int $userId): int
    {
        $row = db_select_one(
            'SELECT COUNT(*) AS `total` FROM `orders` WHERE `user_id` = ?',
            'i',
            array($userId)
        );

        return (int) ($row['total'] ?? 0);
    }

    /**
     * The number of pages needed for a result count.
     *
     * @param int $totalResults
     * @param int $perPage
     * @return int
     */
    public static function pageCount(int $totalResults, int $perPage = self::PER_PAGE): int
    {
        $perPage = max(1, $perPage);

        if ($totalResults <= 0) {
            return 1;
        }

        return (int) ceil($totalResults / $perPage);
    }

    /**
     * Normalise a requested page number to a valid one.
     *
     * @param mixed $requested
     * @param int   $lastPage
     * @return int
     */
    public static function normalisePage($requested, int $lastPage): int
    {
        $lastPage = max(1, $lastPage);

        if (!is_scalar($requested)) {
            return 1;
        }

        $value = trim((string) $requested);

        if ($value === '' || !ctype_digit($value)) {
            return 1;
        }

        $page = (int) $value;

        if ($page < 1) {
            return 1;
        }

        if ($page > $lastPage) {
            return $lastPage;
        }

        return $page;
    }

    // -----------------------------------------------------------------------
    // Writing orders
    // -----------------------------------------------------------------------

    /**
     * Create an order row.
     *
     * The caller runs this inside the checkout transaction, so the order,
     * its items, the stock reduction, the payment row and the cart clearing
     * all succeed together or not at all (FR-4.15).
     *
     * @param string $orderNumber    The human-readable order number.
     * @param int    $userId
     * @param float  $totalAmount
     * @param array<string, mixed> $address The delivery address snapshot.
     * @return int The new order id.
     */
    public static function create(
        string $orderNumber,
        int $userId,
        float $totalAmount,
        array $address
    ): int {
        return db_insert_id(
            "INSERT INTO `orders`
                (`order_number`, `user_id`, `total_amount`, `status`,
                 `delivery_name`, `delivery_phone`, `delivery_address`,
                 `delivery_city`)
             VALUES (?, ?, ?, 'placed', ?, ?, ?, ?)",
            'sidssss',
            array(
                $orderNumber,
                $userId,
                number_format($totalAmount, 2, '.', ''),
                (string) $address['delivery_name'],
                (string) $address['delivery_phone'],
                (string) $address['delivery_address'],
                (string) $address['delivery_city'],
            )
        );
    }

    /**
     * Add one line to an order.
     *
     * The product name and unit price are the purchase-time snapshot
     * (FR-4.12).
     *
     * @param int    $orderId
     * @param int    $productId
     * @param string $productName
     * @param float  $unitPrice
     * @param int    $quantity
     * @return int The new order-item id.
     */
    public static function addItem(
        int $orderId,
        int $productId,
        string $productName,
        float $unitPrice,
        int $quantity
    ): int {
        return db_insert_id(
            'INSERT INTO `order_items`
                (`order_id`, `product_id`, `product_name_at_purchase`,
                 `unit_price_at_purchase`, `quantity`)
             VALUES (?, ?, ?, ?, ?)',
            'iissd',
            array(
                $orderId,
                $productId,
                $productName,
                number_format($unitPrice, 2, '.', ''),
                $quantity,
            )
        );
    }

    /**
     * Write a new fulfilment status onto an order (FR-6.8).
     *
     * The caller is `OrderFulfilment`, which validates the transition
     * before this method is reached and holds the order row locked for the
     * duration of its transaction. This method only performs the write; it
     * deliberately does **not** decide whether the transition is legal,
     * because that decision belongs to one place.
     *
     * The status is bound as a parameter, so it can never be used to
     * inject SQL, and the ENUM column rejects any value outside the five
     * permitted ones.
     *
     * @param int    $orderId
     * @param string $status One of the five permitted statuses.
     * @return void
     */
    public static function updateStatus(int $orderId, string $status): void
    {
        db_write(
            'UPDATE `orders` SET `status` = ? WHERE `id` = ?',
            'si',
            array($status, $orderId)
        );
    }

    /**
     * Lock an order row for the duration of the current transaction.
     *
     * The lock is what stops two Admin requests from changing the same
     * order at the same time. It is held until the transaction ends.
     *
     * @param int $orderId
     * @return array<string, mixed>|null The locked order row, or null when
     *                                   the order does not exist.
     */
    public static function findForUpdate(int $orderId): ?array
    {
        return db_select_one(
            "SELECT o.`id`, o.`order_number`, o.`user_id`, o.`total_amount`,
                    o.`status`, o.`delivery_name`, o.`delivery_phone`,
                    o.`delivery_address`, o.`delivery_city`, o.`created_at`
               FROM `orders` o
              WHERE o.`id` = ?
              FOR UPDATE",
            'i',
            array($orderId)
        );
    }
}
